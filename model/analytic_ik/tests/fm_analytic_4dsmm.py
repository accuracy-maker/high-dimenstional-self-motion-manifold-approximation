T_7_SITE = np.array(
    [
        [-1.0, 0.0, 0.0, 0.000],
        [0.0, -1.0, 0.0, 0.000],
        [0.0, 0.0, 1.0, 0.045],
        [0.0, 0.0, 0.0, 1.000],
    ],
    dtype=float,
)

GC_BRANCHES = tuple(product((-1, 1), repeat=3))
GC_BRANCH_ARRAY = np.asarray(GC_BRANCHES, dtype=int)
BRANCH_LABELS = tuple(
    f"GC=({gc[0]},{gc[1]},{gc[2]})" for gc in GC_BRANCHES
)

COVERAGE_THRESHOLDS = np.array(
    [0.10, 0.25, 0.50, 1.00],
    dtype=float,
)


def to_numpy(value):
    if hasattr(value, "detach"):
        value = value.detach().cpu().numpy()
    return np.asarray(value, dtype=np.float64)


def sample_so3(number, rng):
    """Generate Haar-uniform rotations."""

    if number <= 0:
        raise ValueError("number must be positive")

    u = rng.random((number, 3))
    s = np.sqrt(u[:, 0])
    t = np.sqrt(1.0 - u[:, 0])
    a = 2.0 * np.pi * u[:, 1]
    b = 2.0 * np.pi * u[:, 2]

    x = t * np.sin(a)
    y = t * np.cos(a)
    z = s * np.sin(b)
    w = s * np.cos(b)

    rotations = np.empty((number, 3, 3), dtype=float)
    rotations[:, 0, 0] = 1.0 - 2.0 * (y * y + z * z)
    rotations[:, 0, 1] = 2.0 * (x * y - z * w)
    rotations[:, 0, 2] = 2.0 * (x * z + y * w)
    rotations[:, 1, 0] = 2.0 * (x * y + z * w)
    rotations[:, 1, 1] = 1.0 - 2.0 * (x * x + z * z)
    rotations[:, 1, 2] = 2.0 * (y * z - x * w)
    rotations[:, 2, 0] = 2.0 * (x * z - y * w)
    rotations[:, 2, 1] = 2.0 * (y * z + x * w)
    rotations[:, 2, 2] = 1.0 - 2.0 * (x * x + y * y)
    return rotations


def make_site_pose(position, rotation):
    T = np.eye(4, dtype=float)
    T[:3, :3] = rotation
    T[:3, 3] = position
    return T


def site_pose_to_dh_pose(T_site):
    return np.asarray(T_site, dtype=float) @ np.linalg.inv(T_7_SITE)


def pose_errors(T_a, T_b):
    position_error = np.linalg.norm(T_a[:3, 3] - T_b[:3, 3])
    rotation_error = np.linalg.norm(T_a[:3, :3] - T_b[:3, :3])
    return float(position_error), float(rotation_error)


def fm_condition_from_pose(position, rotation, x_dim):
    if x_dim == 3:
        return np.asarray(position, dtype=float)
    if x_dim == 9:
        return np.concatenate(
            [
                np.asarray(position, dtype=float),
                np.asarray(rotation, dtype=float)[:2].reshape(6),
            ]
        )
    raise ValueError(
        "This comparison supports FM conditioning dimensions 3 and 9, "
        f"but received x_dim={x_dim}."
    )


def mujoco_positions(robot_cfg, qs):
    qs = to_numpy(qs)
    if qs.ndim == 1:
        qs = qs[None, :]
    if qs.ndim != 2 or qs.shape[1] != 7:
        raise ValueError("qs must have shape (N, 7).")

    model = robot_cfg.robot
    data = mujoco.MjData(model)
    qpos_ids = [model.jnt_qposadr[jid] for jid in robot_cfg._jnt_ids]

    if robot_cfg.ee_type == "site":
        ee_id = model.site(robot_cfg.ee_name).id
    elif robot_cfg.ee_type == "body":
        ee_id = model.body(robot_cfg.ee_name).id
    else:
        raise ValueError(f"Invalid ee_type: {robot_cfg.ee_type}")

    positions = np.empty((len(qs), 3), dtype=float)

    for index, q in enumerate(qs):
        data.qpos[:] = 0.0
        data.qpos[qpos_ids] = q
        mujoco.mj_forward(model, data)

        if robot_cfg.ee_type == "site":
            positions[index] = data.site_xpos[ee_id]
        else:
            positions[index] = data.xpos[ee_id]

    return positions


def _empty_branch_counts():
    return {
        "attempted": 0,
        "infeasible": 0,
        "joint_limit_rejected": 0,
        "pose_rejected": 0,
        "exceptions": 0,
        "accepted": 0,
    }


def analytic_smm_samples(
    ik,
    target_position,
    rotations,
    psi_samples,
    *,
    pose_tolerance=1e-5,
    acos_tolerance=1e-8,
    enforce_joint_limits=False,
):
    """Sample the analytical SMM while retaining the GC branch identity."""

    target_position = np.asarray(target_position, dtype=float)
    rotations = np.asarray(rotations, dtype=float)
    psi_samples = np.asarray(psi_samples, dtype=float)

    q_values = []
    orientation_indices = []
    gc_values = []
    psi_values = []

    counts = _empty_branch_counts()
    branch_counts = {
        gc_tuple: _empty_branch_counts() for gc_tuple in GC_BRANCHES
    }

    for orientation_index, rotation in enumerate(rotations):
        T_site = make_site_pose(target_position, rotation)
        T_dh = site_pose_to_dh_pose(T_site)

        for gc_tuple in GC_BRANCHES:
            GC = np.asarray(gc_tuple, dtype=int)
            branch_count = branch_counts[gc_tuple]

            for psi in psi_samples:
                counts["attempted"] += 1
                branch_count["attempted"] += 1

                try:
                    unclipped = np.asarray(
                        ik.IK(
                            rigid_transform=T_dh,
                            GC=GC,
                            psi=float(psi),
                            return_unclipped_vals=True,
                            clip_stepback=0.0,
                        ),
                        dtype=float,
                    )

                    if unclipped.shape != (4,):
                        counts["exceptions"] += 1
                        branch_count["exceptions"] += 1
                        continue

                    if np.any(np.abs(unclipped) > 1.0 + acos_tolerance):
                        counts["infeasible"] += 1
                        branch_count["infeasible"] += 1
                        continue

                    q = np.asarray(
                        ik.IK(
                            rigid_transform=T_dh,
                            GC=GC,
                            psi=float(psi),
                            clip_stepback=0.0,
                        ),
                        dtype=float,
                    )

                    if q.shape != (7,) or not np.all(np.isfinite(q)):
                        counts["pose_rejected"] += 1
                        branch_count["pose_rejected"] += 1
                        continue

                    if enforce_joint_limits:
                        inside_limits = (
                            np.all(q >= ik.limits_lower - 1e-8)
                            and np.all(q <= ik.limits_upper + 1e-8)
                        )
                        if not inside_limits:
                            counts["joint_limit_rejected"] += 1
                            branch_count["joint_limit_rejected"] += 1
                            continue

                    T_check = np.asarray(ik.FK(q), dtype=float)
                    position_error, rotation_error = pose_errors(
                        T_check,
                        T_dh,
                    )

                    if (
                        position_error > pose_tolerance
                        or rotation_error > pose_tolerance
                    ):
                        counts["pose_rejected"] += 1
                        branch_count["pose_rejected"] += 1
                        continue

                    q_values.append(q.copy())
                    orientation_indices.append(orientation_index)
                    gc_values.append(GC.copy())
                    psi_values.append(float(psi))
                    counts["accepted"] += 1
                    branch_count["accepted"] += 1

                except Exception:
                    counts["exceptions"] += 1
                    branch_count["exceptions"] += 1

    q_array = (
        np.asarray(q_values, dtype=float).reshape(-1, 7)
        if q_values
        else np.empty((0, 7), dtype=float)
    )
    orientation_array = np.asarray(orientation_indices, dtype=int)
    gc_array = (
        np.asarray(gc_values, dtype=int).reshape(-1, 3)
        if gc_values
        else np.empty((0, 3), dtype=int)
    )
    psi_array = np.asarray(psi_values, dtype=float)

    branch_qs = {}
    for gc_tuple in GC_BRANCHES:
        mask = np.all(gc_array == np.asarray(gc_tuple), axis=1)
        branch_qs[gc_tuple] = q_array[mask]

    return {
        "q": q_array,
        "orientation_index": orientation_array,
        "GC": gc_array,
        "psi": psi_array,
        "branch_qs": branch_qs,
        "counts": counts,
        "branch_counts": branch_counts,
    }


def torus_embedding(q):
    q = wrap_to_pi(to_numpy(q))
    if q.ndim == 1:
        q = q[None, :]
    return np.concatenate((np.sin(q), np.cos(q)), axis=1)


def nearest_torus_distances(query, reference, candidates=64):
    """Return nearest wrapped joint-space distances."""

    query = to_numpy(query)
    reference = to_numpy(reference)

    if query.ndim == 1:
        query = query[None, :]
    if reference.ndim == 1:
        reference = reference[None, :]
    if len(query) == 0:
        return np.empty((0,), dtype=float)
    if len(reference) == 0:
        return np.full(len(query), np.inf, dtype=float)

    try:
        from scipy.spatial import cKDTree

        tree = cKDTree(torus_embedding(reference))
        k = min(candidates, len(reference))
        _, indices = tree.query(torus_embedding(query), k=k)
        if k == 1:
            indices = indices[:, None]

        valid = indices < len(reference)
        indices = np.clip(indices, 0, len(reference) - 1)
        differences = wrap_to_pi(query[:, None, :] - reference[indices])
        distances = np.linalg.norm(differences, axis=2)
        distances[~valid] = np.inf
        return np.min(distances, axis=1)
    except ImportError:
        result = np.full(len(query), np.inf, dtype=float)
        for start in range(0, len(query), 256):
            stop = min(start + 256, len(query))
            differences = wrap_to_pi(
                query[start:stop, None, :] - reference[None, :, :]
            )
            result[start:stop] = np.min(
                np.linalg.norm(differences, axis=2),
                axis=1,
            )
        return result


def branch_distance_matrix(query, branch_qs, candidates=64):
    if not branch_qs:
        return np.empty((len(query), 0), dtype=float)
    return np.column_stack(
        [
            nearest_torus_distances(
                query,
                branch_qs[gc_tuple],
                candidates=candidates,
            )
            for gc_tuple in GC_BRANCHES
        ]
    )


def _finite_median(values):
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    return float(np.median(values)) if len(values) else np.nan


def _finite_percentile(values, percentile):
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    return float(np.percentile(values, percentile)) if len(values) else np.nan


def _nanmean(values):
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    return float(np.mean(values)) if len(values) else np.nan


def compare_branch_distances(
    corrected_q,
    branch_qs,
    *,
    candidates=64,
):
    """Compute both directions of the comparison for every GC branch."""

    corrected_q = to_numpy(corrected_q)
    if corrected_q.ndim == 1:
        corrected_q = corrected_q[None, :]

    fm_to_branch = branch_distance_matrix(
        corrected_q,
        branch_qs,
        candidates=candidates,
    )

    branch_to_fm = []
    branch_coverage = np.full(
        (len(GC_BRANCHES), len(COVERAGE_THRESHOLDS)),
        np.nan,
        dtype=float,
    )
    fm_to_branch_coverage = np.full_like(branch_coverage, np.nan)
    branch_fm_median = np.full(len(GC_BRANCHES), np.nan, dtype=float)
    branch_fm_p95 = np.full(len(GC_BRANCHES), np.nan, dtype=float)

    for branch_index, gc_tuple in enumerate(GC_BRANCHES):
        branch_q = branch_qs[gc_tuple]
        distances_to_fm = nearest_torus_distances(
            branch_q,
            corrected_q,
            candidates=candidates,
        )
        branch_to_fm.append(distances_to_fm)

        if len(branch_q) > 0:
            branch_coverage[branch_index] = [
                np.mean(distances_to_fm <= threshold)
                for threshold in COVERAGE_THRESHOLDS
            ]
            if len(corrected_q) > 0:
                fm_distances = fm_to_branch[:, branch_index]
                fm_to_branch_coverage[branch_index] = [
                    np.mean(fm_distances <= threshold)
                    for threshold in COVERAGE_THRESHOLDS
                ]

        if len(corrected_q) > 0 and len(branch_q) > 0:
            branch_fm_median[branch_index] = _finite_median(
                fm_to_branch[:, branch_index]
            )
            branch_fm_p95[branch_index] = _finite_percentile(
                fm_to_branch[:, branch_index],
                95.0,
            )

    if len(corrected_q) > 0 and fm_to_branch.shape[1] > 0:
        has_reference = np.any(np.isfinite(fm_to_branch), axis=1)
        nearest_branch_indices = np.full(len(corrected_q), -1, dtype=int)
        nearest_branch_distances = np.full(
            len(corrected_q),
            np.inf,
            dtype=float,
        )
        nearest_branch_indices[has_reference] = np.argmin(
            fm_to_branch[has_reference],
            axis=1,
        )
        nearest_branch_distances[has_reference] = np.min(
            fm_to_branch[has_reference],
            axis=1,
        )
    else:
        nearest_branch_indices = np.empty((0,), dtype=int)
        nearest_branch_distances = np.empty((0,), dtype=float)

    assignment_counts = np.bincount(
        nearest_branch_indices[nearest_branch_indices >= 0],
        minlength=len(GC_BRANCHES),
    )

    analytic_to_fm = (
        np.concatenate(branch_to_fm)
        if branch_to_fm
        else np.empty((0,), dtype=float)
    )

    branch_assigned_median = np.full(len(GC_BRANCHES), np.nan, dtype=float)
    branch_assigned_p95 = np.full(len(GC_BRANCHES), np.nan, dtype=float)
    for branch_index in range(len(GC_BRANCHES)):
        assigned = nearest_branch_indices == branch_index
        branch_assigned_median[branch_index] = _finite_median(
            nearest_branch_distances[assigned]
        )
        branch_assigned_p95[branch_index] = _finite_percentile(
            nearest_branch_distances[assigned],
            95.0,
        )

    coverage = np.array(
        [
            np.mean(analytic_to_fm <= threshold)
            if len(analytic_to_fm) > 0
            else np.nan
            for threshold in COVERAGE_THRESHOLDS
        ],
        dtype=float,
    )

    return {
        "fm_to_branch": fm_to_branch,
        "branch_to_fm": branch_to_fm,
        "nearest_branch_indices": nearest_branch_indices,
        "nearest_branch_distances": nearest_branch_distances,
        "assignment_counts": assignment_counts,
        "branch_coverage": branch_coverage,
        "fm_to_branch_coverage": fm_to_branch_coverage,
        "branch_fm_median": branch_fm_median,
        "branch_fm_p95": branch_fm_p95,
        "branch_assigned_median": branch_assigned_median,
        "branch_assigned_p95": branch_assigned_p95,
        "analytic_to_fm": analytic_to_fm,
        "coverage": coverage,
    }


def evaluate_target(
    fm,
    robot_cfg,
    ik,
    target_position,
    rotations,
    psi_samples,
    *,
    x_dim,
    n_samples,
    n_steps,
    enforce_joint_limits,
    correction_iters=3,
    pose_tolerance=1e-5,
    acos_tolerance=1e-8,
    distance_candidates=64,
):
    analytic = analytic_smm_samples(
        ik=ik,
        target_position=target_position,
        rotations=rotations,
        psi_samples=psi_samples,
        pose_tolerance=pose_tolerance,
        acos_tolerance=acos_tolerance,
        enforce_joint_limits=enforce_joint_limits,
    )

    raw_q_values = []
    valid_orientation_indices = np.unique(analytic["orientation_index"])

    if x_dim == 3:
        valid_orientation_indices = np.array([-1], dtype=int)

    for orientation_index in valid_orientation_indices:
        if orientation_index == -1:
            condition = fm_condition_from_pose(
                target_position,
                np.eye(3),
                x_dim,
            )
        else:
            condition = fm_condition_from_pose(
                target_position,
                rotations[orientation_index],
                x_dim,
            )

        sampled_q = to_numpy(
            fm.sample(
                condition,
                n_samples=n_samples,
                n_steps=n_steps,
            )
        )
        if sampled_q.ndim == 1:
            sampled_q = sampled_q[None, :]
        if sampled_q.ndim != 2 or sampled_q.shape[1] != 7:
            continue

        finite_mask = np.all(np.isfinite(sampled_q), axis=1)
        raw_q_values.append(sampled_q[finite_mask])

    if raw_q_values:
        raw_q = np.concatenate(raw_q_values, axis=0)
    else:
        raw_q = np.empty((0, 7), dtype=float)

    if len(raw_q) > 0:
        corrected_q = correct_positions_mujoco(
            robot_cfg=robot_cfg,
            qs=raw_q,
            target_positions=target_position,
            iters=correction_iters,
            lam=1e-1,
            max_step=0.25,
        )
        corrected_q = to_numpy(corrected_q)
    else:
        corrected_q = np.empty((0, 7), dtype=float)

    if enforce_joint_limits and len(corrected_q) > 0:
        limit_mask = (
            np.all(corrected_q >= ik.limits_lower - 1e-8, axis=1)
            & np.all(corrected_q <= ik.limits_upper + 1e-8, axis=1)
        )
        corrected_q = corrected_q[limit_mask]

    corrected_positions = mujoco_positions(robot_cfg, corrected_q)
    corrected_position_errors = np.linalg.norm(
        corrected_positions - target_position[None, :],
        axis=1,
    )

    branch_result = compare_branch_distances(
        corrected_q,
        analytic["branch_qs"],
        candidates=distance_candidates,
    )

    analytic_branch_counts = np.asarray(
        [
            analytic["branch_counts"][gc_tuple]["accepted"]
            for gc_tuple in GC_BRANCHES
        ],
        dtype=int,
    )
    analytic_branch_attempted = np.asarray(
        [
            analytic["branch_counts"][gc_tuple]["attempted"]
            for gc_tuple in GC_BRANCHES
        ],
        dtype=int,
    )

    return {
        "target_position": np.asarray(target_position, dtype=float),
        "raw_q": raw_q,
        "corrected_q": corrected_q,
        "corrected_position_errors": corrected_position_errors,
        "analytic_q": analytic["q"],
        "analytic_gc": analytic["GC"],
        "analytic_orientation_index": analytic["orientation_index"],
        "analytic_psi": analytic["psi"],
        "analytic_branch_qs": analytic["branch_qs"],
        "analytic_branch_counts": analytic_branch_counts,
        "analytic_branch_attempted": analytic_branch_attempted,
        "fm_to_analytic": branch_result["nearest_branch_distances"],
        "analytic_to_fm": branch_result["analytic_to_fm"],
        "fm_to_branch": branch_result["fm_to_branch"],
        "branch_to_fm": branch_result["branch_to_fm"],
        "nearest_branch_indices": branch_result["nearest_branch_indices"],
        "assignment_counts": branch_result["assignment_counts"],
        "branch_coverage": branch_result["branch_coverage"],
        "fm_to_branch_coverage": branch_result["fm_to_branch_coverage"],
        "branch_fm_median": branch_result["branch_fm_median"],
        "branch_fm_p95": branch_result["branch_fm_p95"],
        "branch_assigned_median": branch_result["branch_assigned_median"],
        "branch_assigned_p95": branch_result["branch_assigned_p95"],
        "coverage": branch_result["coverage"],
        "analytic_counts": analytic["counts"],
        "analytic_branch_counts_detail": analytic["branch_counts"],
    }


def concatenate(results, key, axis=0):
    arrays = [result[key] for result in results if len(result[key]) > 0]
    if not arrays:
        return np.empty((0,), dtype=float)
    return np.concatenate(arrays, axis=axis)


def stack_results(results, key):
    return np.stack([result[key] for result in results], axis=0)


def print_target_branch_summary(result):
    print("  Analytical branches")
    for branch_index, (gc_tuple, label) in enumerate(
        zip(GC_BRANCHES, BRANCH_LABELS)
    ):
        accepted = result["analytic_branch_counts"][branch_index]
        assigned = result["assignment_counts"][branch_index]
        median = result["branch_fm_median"][branch_index]
        p95 = result["branch_fm_p95"][branch_index]
        coverage = result["branch_coverage"][branch_index]
        coverage_text = ", ".join(
            f"{threshold:.2f}:{100.0 * value:.2f}%"
            if np.isfinite(value)
            else f"{threshold:.2f}:n/a"
            for threshold, value in zip(COVERAGE_THRESHOLDS, coverage)
        )
        print(
            f"    {label}: analytic={accepted}, "
            f"FM assigned={assigned}, "
            f"FM->branch median={median:.4f}, p95={p95:.4f}, "
            f"branch->FM [{coverage_text}]"
        )


