    print("Per-branch comparison")
    print(
        "  branch                 analytic    FM assigned    "
        "FM->branch median/p95    branch->FM coverage"
    )
    for branch_index, label in enumerate(BRANCH_LABELS):
        analytic_count = int(np.sum(branch_counts[:, branch_index]))
        assigned_count = int(np.sum(branch_assignments[:, branch_index]))
        assigned_percent = (
            100.0 * assigned_count / total_fm if total_fm > 0 else np.nan
        )
        median = _nanmean(branch_medians[:, branch_index])
        p95 = _nanmean(branch_p95[:, branch_index])
        coverage = np.asarray(branch_coverage[:, branch_index], dtype=float)
        coverage_text = ", ".join(
            f"{threshold:.2f}:{100.0 * _nanmean(coverage[:, k]):.2f}%"
            if np.isfinite(_nanmean(coverage[:, k]))
            else f"{threshold:.2f}:n/a"
            for k, threshold in enumerate(COVERAGE_THRESHOLDS)
        )
        print(
            f"  {label:<22} {analytic_count:>8d}    "
            f"{assigned_count:>8d} ({assigned_percent:>6.2f}%)    "
            f"{median:>8.4f}/{p95:<8.4f}       {coverage_text}"
        )


