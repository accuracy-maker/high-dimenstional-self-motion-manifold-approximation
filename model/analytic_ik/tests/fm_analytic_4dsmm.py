def evaluate_4d(
    cfg,
    *,
    n_targets=1,
    n_samples=200_000,
    n_steps=100,
    n_analytic_orientations=512,
    n_analytic_psi=512,
    seed=42,
    enforce_joint_limits=False,
    correction_iters=3,
    pose_tolerance=1e-5,
    acos_tolerance=1e-8,
    distance_candidates=64,
    output_path="evaluation/fm_vs_analytic_4d_branches.png",
    metrics_path=None,
    projection=(5, 6),
):
    robot_cfg = cfg.load_robot

    if robot_cfg.x_dim not in (3, 9):
        raise ValueError(
            "This comparison expects a 3-D or 9-D FM task, "
            f"but x_dim={robot_cfg.x_dim}."
        )

    if robot_cfg.ee_type != "site":
        raise ValueError(
            "The analytical frame conversion in this file is calibrated "
            "for the MuJoCo end-effector site."
        )

    train, test, norm = load_data(cfg)
    del train

    test_targets = to_numpy(test.tensors[1])
    x_c = to_numpy(norm["x_c"])
    x_h = to_numpy(norm["x_h"])
    test_targets = test_targets * x_h + x_c
    test_targets = np.asarray(test_targets[:, :3], dtype=float)

    if len(test_targets) == 0:
        raise ValueError("The test set contains no target positions.")
    if n_targets <= 0:
        raise ValueError("n_targets must be positive.")

    rng = np.random.default_rng(seed)
    n_targets = min(n_targets, len(test_targets))
    selected_indices = rng.choice(
        len(test_targets),
        size=n_targets,
        replace=False,
    )
    test_targets = test_targets[selected_indices]

    rotations = sample_so3(n_analytic_orientations, rng)
    psi_samples = np.linspace(
        -np.pi,
        np.pi,
        n_analytic_psi,
        endpoint=False,
    )

    solver_kwargs = {}
    if enforce_joint_limits and hasattr(robot_cfg, "q_min"):
        solver_kwargs["limits_lower"] = robot_cfg.q_min
        solver_kwargs["limits_upper"] = robot_cfg.q_max
    ik_solver = Analytical_IK_7DoF(**solver_kwargs)

    fm = FlowMatching(cfg, norm)
    fm.load()
    print("Model loaded.")
    print(f"FM conditioning dimension: {robot_cfg.x_dim}")
    print(f"Targets: {len(test_targets)}")
    print(
        "Analytical reference samples per target before filtering: "
        f"{len(GC_BRANCHES) * n_analytic_orientations * n_analytic_psi}"
    )

    results = []
    for target_index, target_position in enumerate(test_targets):
        result = evaluate_target(
            fm=fm,
            robot_cfg=robot_cfg,
            ik=ik_solver,
            target_position=target_position,
            rotations=rotations,
            psi_samples=psi_samples,
            x_dim=robot_cfg.x_dim,
            n_samples=n_samples,
            n_steps=n_steps,
            enforce_joint_limits=enforce_joint_limits,
            correction_iters=correction_iters,
            pose_tolerance=pose_tolerance,
            acos_tolerance=acos_tolerance,
            distance_candidates=distance_candidates,
        )
        results.append(result)

        position_median = _finite_median(
            result["corrected_position_errors"]
        )
        print(
            f"Target {target_index + 1}/{len(test_targets)}: "
            f"corrected FM samples={len(result['corrected_q'])}, "
            f"analytic samples={len(result['analytic_q'])}, "
            f"position median={position_median:.3e} m"
        )
        print_target_branch_summary(result)

    print_summary(results)
    plot_comparison(results, output_path, projection=projection)

    if metrics_path is None:
        metrics_path = Path(output_path).with_suffix(".npz")
    save_metrics(results, metrics_path)

    print(f"Saved figure to: {output_path}")
    print(
        "Saved branch projection figure to: "
        f"{Path(output_path).with_name(Path(output_path).stem + '_joint_projection' + Path(output_path).suffix)}"
    )
    print(f"Saved metrics to: {metrics_path}")
    return results


