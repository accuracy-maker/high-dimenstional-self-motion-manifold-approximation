def plot_branch_joint_projection(results, output_path, projection=(5, 6)):
    """Plot analytical and assigned FM samples for every branch."""

    joint_x, joint_y = projection
    if not (0 <= joint_x < 7 and 0 <= joint_y < 7):
        raise ValueError("projection joints must be in [0, 6]")
    if joint_x == joint_y:
        raise ValueError("projection joints must be different")

    fig, axes = plt.subplots(2, 4, figsize=(16, 8), squeeze=False)
    max_points = 20_000

    for branch_index, (gc_tuple, label) in enumerate(
        zip(GC_BRANCHES, BRANCH_LABELS)
    ):
        ax = axes.ravel()[branch_index]
        for result in results:
            analytic_q = result["analytic_branch_qs"][gc_tuple]
            assigned = result["nearest_branch_indices"] == branch_index
            fm_q = result["corrected_q"][assigned]

            if len(analytic_q) > max_points:
                analytic_q = analytic_q[
                    np.linspace(
                        0,
                        len(analytic_q) - 1,
                        max_points,
                    ).astype(int)
                ]
            if len(fm_q) > max_points:
                fm_q = fm_q[
                    np.linspace(
                        0,
                        len(fm_q) - 1,
                        max_points,
                    ).astype(int)
                ]

            if len(analytic_q) > 0:
                ax.scatter(
                    wrap_to_pi(analytic_q[:, joint_x]),
                    wrap_to_pi(analytic_q[:, joint_y]),
                    s=2,
                    alpha=0.18,
                    color="tab:blue",
                    label="analytic" if result is results[0] else None,
                )
            if len(fm_q) > 0:
                ax.scatter(
                    wrap_to_pi(fm_q[:, joint_x]),
                    wrap_to_pi(fm_q[:, joint_y]),
                    s=2,
                    alpha=0.18,
                    color="tab:orange",
                    label="corrected FM" if result is results[0] else None,
                )

        ax.set_title(label)
        ax.set_xlim(-np.pi, np.pi)
        ax.set_ylim(-np.pi, np.pi)
        ax.set_xlabel(rf"$\theta_{{{joint_x + 1}}}$")
        ax.set_ylabel(rf"$\theta_{{{joint_y + 1}}}$")
        ax.grid(alpha=0.25)
        if branch_index == 0:
            ax.legend(markerscale=4)

    fig.suptitle(
        "Branch-wise analytical and corrected FM samples "
        f"($theta_{{{joint_x + 1}}}$ vs $theta_{{{joint_y + 1}}}$)",
        fontsize=14,
    )
    fig.tight_layout()
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    # fig.savefig(output_path.with_suffix(".pdf"), bbox_inches="tight")
    plt.close(fig)


